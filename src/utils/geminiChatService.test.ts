test('callGeminiWithFallbackAndRetry retries on 503 and returns primary if retry succeeds', async () => {
  let callCount = 0;
  const mockAi = {
    models: {
      generateContent: async ({ model }: { model: string }) => {
        callCount++;
        if (callCount === 1) {
          const err = new Error('This model is currently experiencing high demand.');
          (err as unknown as { status: number }).status = 503;
          throw err;
        }
        return { text: `Success on retry by ${model}` };
      },
    },
  } as unknown as GoogleGenAI;

  const result = await callGeminiWithFallbackAndRetry({
    ai: mockAi,
    contents: [{ role: 'user', parts: [{ text: 'Hello' }] }],
    systemInstruction: 'Instruction',
    primaryModel: 'gemini-3.5-flash-lite',
    fallbackModel: 'gemini-3.1-flash-lite',
    maxPrimaryRetries: 2,
    sleepFn: async () => {},
    logger: { info: () => {}, warn: () => {}, error: () => {} },
  });

  assert.equal(result.model, 'gemini-3.5-flash-lite');
  assert.equal(result.usedFallback, false);
  assert.equal(result.retriesUsed, 1);
  assert.equal(result.text, 'Success on retry by gemini-3.5-flash-lite');
});

test('callGeminiWithFallbackAndRetry switches to fallback model gemini-3.1-flash-lite when primary 3.5 is overloaded (503)', async () => {
  const attemptedModels: string[] = [];

  const mockAi = {
    models: {
      generateContent: async ({ model }: { model: string }) => {
        attemptedModels.push(model);
        if (model === 'gemini-3.5-flash-lite') {
          const err = new Error('This model is currently experiencing high demand.');
          (err as unknown as { status: number }).status = 503;
          throw err;
        }
        return { text: 'Recovered response via fallback' };
      },
    },
  } as unknown as GoogleGenAI;

  const result = await callGeminiWithFallbackAndRetry({
    ai: mockAi,
    contents: [{ role: 'user', parts: [{ text: 'Test' }] }],
    systemInstruction: 'Instruction',
    primaryModel: 'gemini-3.5-flash-lite',
    fallbackModel: 'gemini-3.1-flash-lite',
    maxPrimaryRetries: 2,
    sleepFn: async () => {},
    logger: { info: () => {}, warn: () => {}, error: () => {} },
  });

  assert.equal(result.model, 'gemini-3.1-flash-lite');
  assert.equal(result.usedFallback, true);
  assert.equal(result.text, 'Recovered response via fallback');
  // 3 attempts on 3.5 (initial + 2 retries), then 1 on 3.1
  assert.equal(attemptedModels.filter((m) => m === 'gemini-3.5-flash-lite').length, 3);
  assert.equal(attemptedModels.filter((m) => m === 'gemini-3.1-flash-lite').length, 1);
});

test('callGeminiWithFallbackAndRetry halts immediately without retrying on 401 invalid credentials', async () => {
  let calls = 0;
  const mockAi = {
    models: {
      generateContent: async () => {
        calls++;
        const err = new Error('API_KEY_INVALID');
        (err as unknown as { status: number }).status = 401;
        throw err;
      },
    },
  } as unknown as GoogleGenAI;

  await assert.rejects(
    async () => {
      await callGeminiWithFallbackAndRetry({
        ai: mockAi,
        contents: [{ role: 'user', parts: [{ text: 'Test' }] }],
        systemInstruction: 'Instruction',
        primaryModel: 'gemini-3.8-flash',
        fallbackModel: 'gemini-3.6-flash',
        maxPrimaryRetries: 3,
        sleepFn: async () => {},
        logger: { info: () => {}, warn: () => {}, error: () => {} },
      });
    },
    (err: Error) => {
      assert.equal((err as unknown as { status: number }).status, 401);
      return true;
    }
  );

  // Exactly 1 call, zero retries
  assert.equal(calls, 1);
});
