import test from 'node:test';
import assert from 'node:assert/strict';
import {
  isRetryableError,
  extractRetryAfterMs,
  calculateBackoffWithJitter,
  callGeminiWithFallbackAndRetry,
} from './geminiChatService.ts';
import { GoogleGenAI } from '@google/genai';

test('isRetryableError classifies transient vs permanent errors accurately', () => {
  // Retryable errors
  assert.equal(isRetryableError({ status: 503, message: 'The model is overloaded' }), true);
  assert.equal(isRetryableError({ status: 502, message: 'Bad Gateway' }), true);
  assert.equal(isRetryableError({ status: 504, message: 'Gateway Timeout' }), true);
  assert.equal(isRetryableError({ status: 429, message: 'Resource exhausted' }), true);
  assert.equal(isRetryableError(new Error('This model is currently experiencing high demand. Spikes in demand are usually temporary.')), true);
  assert.equal(isRetryableError(new Error('fetch failed: ECONNRESET')), true);

  // Non-retryable errors
  assert.equal(isRetryableError({ status: 400, message: 'INVALID_ARGUMENT: contents must not be empty' }), false);
  assert.equal(isRetryableError({ status: 401, message: 'API_KEY_INVALID' }), false);
  assert.equal(isRetryableError({ status: 403, message: 'PERMISSION_DENIED: caller lacks permission' }), false);
  assert.equal(isRetryableError({ status: 404, message: 'Model not found' }), false);
});

test('extractRetryAfterMs parses numeric and header values with capping', () => {
  assert.equal(extractRetryAfterMs({ headers: { 'retry-after': '3' } }), 3000);
  assert.equal(extractRetryAfterMs({ message: 'Rate limit exceeded. Retry-After: 2' }), 2000);
  // Capped at 5000ms
  assert.equal(extractRetryAfterMs({ headers: { 'retry-after': '60' } }), 5000);
  assert.equal(extractRetryAfterMs({}), null);
});

test('calculateBackoffWithJitter returns bounded exponential value with jitter', () => {
  const d0 = calculateBackoffWithJitter(0, 500, 3000, 100);
  assert.ok(d0 >= 500 && d0 <= 600);

  const d1 = calculateBackoffWithJitter(1, 500, 3000, 100);
  assert.ok(d1 >= 1000 && d1 <= 1100);

  const dMax = calculateBackoffWithJitter(10, 500, 2000, 100);
  assert.equal(dMax, 2000);
});

